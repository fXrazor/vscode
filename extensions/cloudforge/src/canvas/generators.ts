// Phase 9 Follow-On: Multi-Target IaC Generator Adapters (Azure Bicep, Azure ARM JSON,
// AWS CloudFormation YAML, and Kubernetes YAML) with explicit semantic mapping coverage
// and honest loss reporting. Pure TypeScript with zero DOM or `vscode` runtime dependencies.

import type { CanvasGraphSnapshot, CanvasNodeSummary } from './protocol';
import type { DraftValue, ResourceDraft } from './schemaForm';

export type GeneratorTarget = 'bicep' | 'arm' | 'cloudformation' | 'k8s';

export interface GeneratedTargetArtifact {
	readonly target: GeneratorTarget;
	readonly label: string;
	readonly fileExtension: '.bicep' | '.json' | '.yaml';
	readonly provenance: string;
	readonly sourceRevision: string;
	readonly mappedCount: number;
	readonly unmappedCount: number;
	readonly unmappedTypes: readonly string[];
	readonly lossNotes: readonly string[];
	readonly code: string;
}

export const GENERATOR_PROVENANCE = 'CloudForge Static Multi-Target Mapper (v1.0, offline preview)';

function sanitizeSymbol(raw: string, fallback = 'res'): string {
	const cleaned = raw.replace(/[^A-Za-z0-9_]/g, '_').replace(/^[^A-Za-z_]+/, '');
	return cleaned.length > 0 ? cleaned : fallback;
}

function pascalSymbol(raw: string): string {
	const parts = raw.split(/[^A-Za-z0-9]+/).filter(Boolean);
	const joined = parts.map(p => p.charAt(0).toUpperCase() + p.slice(1)).join('');
	return /^[A-Za-z]/.test(joined) ? joined : `Res${joined || 'Item'}`;
}

function literalString(draft: ResourceDraft | undefined, key: string, fallback: string): string {
	const val: DraftValue | undefined = draft?.attributes[key];
	if (val?.kind === 'literal' && typeof val.value === 'string' && val.value.trim().length > 0) {
		return val.value.trim();
	}
	return fallback;
}

function literalList(draft: ResourceDraft | undefined, key: string, fallback: readonly string[]): readonly string[] {
	const val: DraftValue | undefined = draft?.attributes[key];
	if (val?.kind === 'literal' && Array.isArray(val.value) && val.value.length > 0) {
		return val.value.map(String);
	}
	return fallback;
}

function generateBicep(graph: CanvasGraphSnapshot, drafts: Readonly<Record<string, ResourceDraft>>): GeneratedTargetArtifact {
	const lines: string[] = [
		`// Generated by ${GENERATOR_PROVENANCE}`,
		`// Architecture: ${graph.architectureName} · Source rev: ${graph.sourceRevision.slice(0, 8)}`,
		`targetScope = 'resourceGroup'`,
		'',
		`param location string = resourceGroup().location`,
		'',
	];
	let mappedCount = 0;
	const unmappedTypes = new Set<string>();
	const lossNotes: string[] = [];

	for (const node of graph.nodes) {
		const type = (node.resourceType ?? '').toLowerCase();
		const draft = drafts[node.id];
		const sym = sanitizeSymbol(node.name, 'resource');
		const resName = literalString(draft, 'name', node.name.replace(/_/g, '-'));

		if (type === 'azurerm_resource_group') {
			mappedCount++;
			lines.push(`// Resource Group '${resName}' is represented by targetScope = 'resourceGroup'.`, '');
		} else if (type === 'azurerm_virtual_network') {
			mappedCount++;
			const prefixes = literalList(draft, 'address_space', ['10.0.0.0/16']).map(p => `'${p}'`).join(', ');
			lines.push(
				`resource ${sym} 'Microsoft.Network/virtualNetworks@2024-01-01' = {`,
				`  name: '${resName}'`,
				`  location: location`,
				`  properties: {`,
				`    addressSpace: {`,
				`      addressPrefixes: [${prefixes}]`,
				`    }`,
				`  }`,
				`}`,
				''
			);
		} else if (type === 'azurerm_subnet') {
			mappedCount++;
			const prefix = literalList(draft, 'address_prefixes', ['10.0.1.0/24'])[0];
			lines.push(
				`// Subnet '${resName}' (attach parent VNet symbol before deployment)`,
				`resource ${sym} 'Microsoft.Network/virtualNetworks/subnets@2024-01-01' = {`,
				`  name: 'vnet/${resName}'`,
				`  properties: {`,
				`    addressPrefix: '${prefix}'`,
				`  }`,
				`}`,
				''
			);
			lossNotes.push(`Subnet ${node.label} uses placeholder parent VNet prefix; review parent VNet symbol before deploying.`);
		} else if (type === 'azurerm_network_security_group') {
			mappedCount++;
			lines.push(
				`resource ${sym} 'Microsoft.Network/networkSecurityGroups@2024-01-01' = {`,
				`  name: '${resName}'`,
				`  location: location`,
				`  properties: {}`,
				`}`,
				''
			);
		} else if (type === 'azurerm_public_ip') {
			mappedCount++;
			const sku = literalString(draft, 'sku', 'Standard');
			const alloc = literalString(draft, 'allocation_method', 'Static');
			lines.push(
				`resource ${sym} 'Microsoft.Network/publicIPAddresses@2024-01-01' = {`,
				`  name: '${resName}'`,
				`  location: location`,
				`  sku: {`,
				`    name: '${sku}'`,
				`  }`,
				`  properties: {`,
				`    publicIPAllocationMethod: '${alloc}'`,
				`  }`,
				`}`,
				''
			);
		} else if (type === 'azurerm_route_table') {
			mappedCount++;
			lines.push(
				`resource ${sym} 'Microsoft.Network/routeTables@2024-01-01' = {`,
				`  name: '${resName}'`,
				`  location: location`,
				`  properties: {}`,
				`}`,
				''
			);
		} else {
			unmappedTypes.add(node.resourceType ?? node.kind);
			lines.push(`// Unmapped declaration skipped: ${node.label} (${node.resourceType ?? node.kind})`, '');
		}
	}

	const unmappedCount = graph.nodes.length - mappedCount;
	if (unmappedCount > 0) {
		lossNotes.push(`${unmappedCount} declaration(s) have no static Bicep mapping and were emitted as comments.`);
	}
	return {
		target: 'bicep',
		label: 'Azure Bicep',
		fileExtension: '.bicep',
		provenance: GENERATOR_PROVENANCE,
		sourceRevision: graph.sourceRevision,
		mappedCount,
		unmappedCount,
		unmappedTypes: [...unmappedTypes].sort(),
		lossNotes,
		code: lines.join('\n').trimEnd() + '\n',
	};
}

function generateArm(graph: CanvasGraphSnapshot, drafts: Readonly<Record<string, ResourceDraft>>): GeneratedTargetArtifact {
	const resources: Record<string, unknown>[] = [];
	let mappedCount = 0;
	const unmappedTypes = new Set<string>();
	const lossNotes: string[] = [];

	for (const node of graph.nodes) {
		const type = (node.resourceType ?? '').toLowerCase();
		const draft = drafts[node.id];
		const resName = literalString(draft, 'name', node.name.replace(/_/g, '-'));

		if (type === 'azurerm_resource_group') {
			mappedCount++;
			lossNotes.push(`Resource Group ${node.label} maps to deployment target scope rather than an ARM resource entry.`);
		} else if (type === 'azurerm_virtual_network') {
			mappedCount++;
			resources.push({
				type: 'Microsoft.Network/virtualNetworks',
				apiVersion: '2024-01-01',
				name: resName,
				location: '[parameters(\'location\')]',
				properties: {
					addressSpace: { addressPrefixes: [...literalList(draft, 'address_space', ['10.0.0.0/16'])] },
				},
			});
		} else if (type === 'azurerm_network_security_group') {
			mappedCount++;
			resources.push({
				type: 'Microsoft.Network/networkSecurityGroups',
				apiVersion: '2024-01-01',
				name: resName,
				location: '[parameters(\'location\')]',
				properties: {},
			});
		} else if (type === 'azurerm_public_ip') {
			mappedCount++;
			resources.push({
				type: 'Microsoft.Network/publicIPAddresses',
				apiVersion: '2024-01-01',
				name: resName,
				location: '[parameters(\'location\')]',
				sku: { name: literalString(draft, 'sku', 'Standard') },
				properties: { publicIPAllocationMethod: literalString(draft, 'allocation_method', 'Static') },
			});
		} else if (type === 'azurerm_route_table') {
			mappedCount++;
			resources.push({
				type: 'Microsoft.Network/routeTables',
				apiVersion: '2024-01-01',
				name: resName,
				location: '[parameters(\'location\')]',
				properties: {},
			});
		} else {
			unmappedTypes.add(node.resourceType ?? node.kind);
		}
	}

	const unmappedCount = graph.nodes.length - mappedCount;
	if (unmappedCount > 0) {
		lossNotes.push(`${unmappedCount} declaration(s) have no static ARM template mapping.`);
	}
	const template = {
		$schema: 'https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#',
		contentVersion: '1.0.0.0',
		metadata: {
			generator: GENERATOR_PROVENANCE,
			architecture: graph.architectureName,
			sourceRevision: graph.sourceRevision.slice(0, 8),
		},
		parameters: {
			location: {
				type: 'string',
				defaultValue: '[resourceGroup().location]',
			},
		},
		resources,
	};

	return {
		target: 'arm',
		label: 'Azure ARM JSON',
		fileExtension: '.json',
		provenance: GENERATOR_PROVENANCE,
		sourceRevision: graph.sourceRevision,
		mappedCount,
		unmappedCount,
		unmappedTypes: [...unmappedTypes].sort(),
		lossNotes,
		code: JSON.stringify(template, null, 2) + '\n',
	};
}

function generateCloudFormation(graph: CanvasGraphSnapshot): GeneratedTargetArtifact {
	const lines: string[] = [
		`# Generated by ${GENERATOR_PROVENANCE}`,
		`# Architecture: ${graph.architectureName} · Source rev: ${graph.sourceRevision.slice(0, 8)}`,
		`AWSTemplateFormatVersion: '2010-09-09'`,
		`Description: CloudForge CloudFormation export for ${graph.architectureName}`,
		`Resources:`,
	];
	let mappedCount = 0;
	const unmappedTypes = new Set<string>();

	const emitCfn = (node: CanvasNodeSummary, cfnType: string, props: readonly string[]) => {
		mappedCount++;
		lines.push(`  ${pascalSymbol(node.name)}:`, `    Type: ${cfnType}`, `    Properties:`);
		for (const p of props) {
			lines.push(`      ${p}`);
		}
	};

	for (const node of graph.nodes) {
		const type = (node.resourceType ?? '').toLowerCase();
		if (type === 'aws_vpc') {
			emitCfn(node, 'AWS::EC2::VPC', [`CidrBlock: '10.20.0.0/16'`, `EnableDnsHostnames: true`]);
		} else if (type === 'aws_subnet') {
			emitCfn(node, 'AWS::EC2::Subnet', [`CidrBlock: '10.20.1.0/24'`, `VpcId: !Ref Main`]);
		} else if (type === 'aws_internet_gateway') {
			emitCfn(node, 'AWS::EC2::InternetGateway', [`Tags: [{ Key: Name, Value: '${node.name}' }]`]);
		} else if (type === 'aws_security_group') {
			emitCfn(node, 'AWS::EC2::SecurityGroup', [`GroupDescription: 'CloudForge security group ${node.name}'`]);
		} else {
			unmappedTypes.add(node.resourceType ?? node.kind);
		}
	}

	if (mappedCount === 0) {
		lines.push(`  # No AWS resources with static CloudFormation mappings in this architecture.`);
	}
	const unmappedCount = graph.nodes.length - mappedCount;
	const lossNotes = unmappedCount > 0
		? [`${unmappedCount} non-AWS or unmapped declaration(s) omitted from CloudFormation output.`]
		: [];
	return {
		target: 'cloudformation',
		label: 'AWS CloudFormation YAML',
		fileExtension: '.yaml',
		provenance: GENERATOR_PROVENANCE,
		sourceRevision: graph.sourceRevision,
		mappedCount,
		unmappedCount,
		unmappedTypes: [...unmappedTypes].sort(),
		lossNotes,
		code: lines.join('\n') + '\n',
	};
}

function generateKubernetes(graph: CanvasGraphSnapshot): GeneratedTargetArtifact {
	const docs: string[] = [];
	let mappedCount = 0;
	const unmappedTypes = new Set<string>();

	for (const node of graph.nodes) {
		const type = (node.resourceType ?? '').toLowerCase();
		const k8sName = node.name.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
		if (type === 'kubernetes_namespace' || type === 'kubernetes_namespace_v1') {
			mappedCount++;
			docs.push([
				`apiVersion: v1`,
				`kind: Namespace`,
				`metadata:`,
				`  name: ${k8sName}`,
			].join('\n'));
		} else if (type === 'kubernetes_config_map' || type === 'kubernetes_config_map_v1') {
			mappedCount++;
			docs.push([
				`apiVersion: v1`,
				`kind: ConfigMap`,
				`metadata:`,
				`  name: ${k8sName}`,
				`data: {}`,
			].join('\n'));
		} else if (type === 'kubernetes_network_policy' || type === 'kubernetes_network_policy_v1') {
			mappedCount++;
			docs.push([
				`apiVersion: networking.k8s.io/v1`,
				`kind: NetworkPolicy`,
				`metadata:`,
				`  name: ${k8sName}`,
				`spec:`,
				`  podSelector: {}`,
				`  policyTypes:`,
				`    - Ingress`,
			].join('\n'));
		} else {
			unmappedTypes.add(node.resourceType ?? node.kind);
		}
	}

	const header = `# Generated by ${GENERATOR_PROVENANCE}\n# Architecture: ${graph.architectureName} · Source rev: ${graph.sourceRevision.slice(0, 8)}\n`;
	const body = docs.length > 0
		? docs.join('\n---\n') + '\n'
		: `# No Kubernetes declarations with static YAML mappings in this architecture.\n`;
	const unmappedCount = graph.nodes.length - mappedCount;
	const lossNotes = unmappedCount > 0
		? [`${unmappedCount} non-Kubernetes or unmapped declaration(s) omitted from Kubernetes YAML output.`]
		: [];
	return {
		target: 'k8s',
		label: 'Kubernetes YAML',
		fileExtension: '.yaml',
		provenance: GENERATOR_PROVENANCE,
		sourceRevision: graph.sourceRevision,
		mappedCount,
		unmappedCount,
		unmappedTypes: [...unmappedTypes].sort(),
		lossNotes,
		code: header + body,
	};
}

/** Generates a deterministic multi-target IaC artifact with honest coverage and loss reporting. */
export function generateTargetIac(
	graph: CanvasGraphSnapshot,
	drafts: Readonly<Record<string, ResourceDraft>>,
	target: GeneratorTarget
): GeneratedTargetArtifact {
	switch (target) {
		case 'bicep': return generateBicep(graph, drafts);
		case 'arm': return generateArm(graph, drafts);
		case 'cloudformation': return generateCloudFormation(graph);
		case 'k8s': return generateKubernetes(graph);
	}
}
