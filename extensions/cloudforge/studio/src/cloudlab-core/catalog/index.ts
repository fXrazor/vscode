// CloudForge's selected imported schema supplies field types to both forms and HCL projection.
// It cannot introduce inferred placement, inheritance or provider authorization rules.
const formSchemas = new Map<string, ResourceDef>();
export function clearFormAttributes(type?: string): void {
  if (type) formSchemas.delete(type); else formSchemas.clear();
  changed();
}
export function registerFormAttributes(type: string, provider: ProviderId, attributes: AttrDef[]): void {
  const base = generated.get(type) ?? byType.get(type);
  formSchemas.set(type, {
    type, provider, service: 'Imported schema', category: 'Other', displayName: type, icon: '',
    parents: provider === 'azurerm' ? ['azurerm_resource_group'] : [], inherit: [], exported: [], learn: '', docPath: '',
    ...base, attributes,
  });
  changed();
}

// ---------- Full provider index (generated by scripts/build-provider-index.ts) ----------
//
// Every resource type in the local provider documentation is listed in a light search index
// (public/catalog/<provider>/index.json). The full definition of a type (its arguments, blocks,
// references) lives in one file per service and is loaded the first time the type is used.
// CloudForge adaptation: loaded documentation fills the full field tree for curated types too.
// Reviewed placement/inheritance rules remain curated; only the form metadata is enriched.

/** What the library shows for a type before its full definition is loaded. */
export interface CatalogEntry {
  type: string;
  provider: ProviderId;
  displayName: string;
  category: string;
  service: string;
  icon: string;
  container?: boolean;
  aliases?: string[];
  learn?: string;
  generated?: boolean;
  iconMatch?: ResourceDef["iconMatch"];
  /** Service file holding the full definition (generated entries only). */
  shard?: string;
}

type IndexedProvider = Exclude<ProviderId, "kubernetes">;
export const indexedProviders: IndexedProvider[] = ["azurerm", "aws", "google"];

/** Reads a file below the catalogue root (a URL in the browser, a file in tests and scripts). */
export type CatalogReader = (path: string) => Promise<unknown>;
let reader: CatalogReader = async (path) => {
  const response = await fetch(`/catalog/${path}`);
  if (!response.ok) throw new Error(`Catalogue file ${path} could not be loaded (${response.status}).`);
  return response.json();
};
export const setCatalogReader = (r: CatalogReader) => {
  reader = r;
};

const generated = new Map<string, ResourceDef>();
const entries = new Map<string, CatalogEntry>();
const indexVersions: Partial<Record<IndexedProvider, string>> = {};
/** Documentation service (and category) of hand-written types, from the provider index. */
const curatedService = new Map<string, { service: string; category: string }>();
const indexLoads = new Map<IndexedProvider, Promise<void>>();
const shardLoads = new Map<string, Promise<void>>();
const failures = new Map<string, string>();
let revision = 0;
const listeners = new Set<() => void>();
const changed = () => {
  revision++;
  for (const l of listeners) l();
};

/** Re-render hook plumbing (useSyncExternalStore). */
export const subscribeCatalog = (fn: () => void) => {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
};
export const catalogRevision = () => revision;
export const catalogFailures = () => [...failures.values()];
export const indexedVersion = (p: ProviderId) => indexVersions[p as IndexedProvider];
export const providerIndexLoaded = (p: ProviderId) => !!indexVersions[p as IndexedProvider];

const providerOfType = (type: string): IndexedProvider | undefined =>
  indexedProviders.find((p) => type.startsWith(`${p}_`));

/** Load the light search index of one provider (once). */
export function loadProviderIndex(provider: ProviderId): Promise<void> {
  if (provider === "kubernetes") return Promise.resolve();
  const existing = indexLoads.get(provider);
  if (existing) return existing;
  const load = (async () => {
    try {
      const data = (await reader(`${provider}/index.json`)) as {
        version: string;
        entries: [string, string, string, string, string, CatalogEntry["iconMatch"], string][];
        curated?: [string, string, string][];
      };
      for (const [type, service, category] of data.curated ?? []) curatedService.set(type, { service, category });
      for (const [type, displayName, category, service, icon, iconMatch, shard] of data.entries) {
        entries.set(type, { type, provider, displayName, category, service, icon, iconMatch, shard, generated: true });
      }
      indexVersions[provider] = data.version;
      failures.delete(provider);
      changed();
    } catch (e) {
      indexLoads.delete(provider);
      failures.set(provider, `${providers[provider].label}: ${(e as Error).message}`);
      changed();
    }
  })();
  indexLoads.set(provider, load);
  return load;
}

/** Make sure the full definitions of these types are loaded. Unknown types are ignored. */
export async function ensureTypes(types: Iterable<string | undefined>): Promise<void> {
  const wanted = [...new Set([...types].filter((t): t is string => !!t && !generated.has(t)))];
  if (!wanted.length) return;
  await Promise.all([...new Set(wanted.map(providerOfType).filter((p): p is IndexedProvider => !!p))].map(loadProviderIndex));
  const shards = new Set<string>();
  for (const t of wanted) {
    const e = entries.get(t);
    if (e?.shard) shards.add(`${e.provider}/${e.shard}`);
  }
  await Promise.all(
    [...shards].map((key) => {
      let load = shardLoads.get(key);
      if (!load) {
        load = (async () => {
          try {
            const data = (await reader(`${key}.json`)) as { resources: ResourceDef[] };
            for (const def of data.resources) {
              const curated = byType.get(def.type);
              generated.set(def.type, { ...curated, ...def, ...(curated ? { parents: curated.parents, inherit: curated.inherit, container: curated.container } : {}), generated: true });
              const form = formSchemas.get(def.type);
              if (form) formSchemas.set(def.type, { ...generated.get(def.type)!, attributes: form.attributes });
            }
            failures.delete(key);
            changed();
          } catch (e) {
            shardLoads.delete(key);
            failures.set(key, `${key}: ${(e as Error).message}`);
            changed();
          }
        })();
        shardLoads.set(key, load);
      }
      return load;
    }),
  );
}

/** Resource types named in Terraform text (resource and data blocks), to load before importing. */
export function typesInTerraform(files: Record<string, string> | string): string[] {
  const text = typeof files === "string" ? files : Object.values(files).join("\n");
  return [...new Set([...text.matchAll(/^\s*(?:resource|data)\s+"([a-z0-9_]+)"/gm)].map((m) => m[1]!))];
}

const curatedEntry = (r: ResourceDef): CatalogEntry => {
  const doc = curatedService.get(r.type);
  return doc ? { ...r, service: doc.service, category: doc.category } : r;
};

/** Everything the library can show: hand-written definitions plus loaded provider indexes. */
export function catalogEntries(provider?: ProviderId): CatalogEntry[] {
  const curated = resources.filter((r) => !provider || r.provider === provider).map(curatedEntry);
  const rest = [...entries.values()].filter((e) => !byType.has(e.type) && (!provider || e.provider === provider));
  return [...curated, ...rest];
}
export const getEntry = (type: string): CatalogEntry | undefined => {
  const r = byType.get(type);
  return r ? curatedEntry(r) : entries.get(type);
};

