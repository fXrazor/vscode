/** Find the definition of a (possibly nested, dotted) attribute. */
export function findAttr(def: ResourceDef, path: string): AttrDef | undefined {
  let list: AttrDef[] | undefined = def.attributes;
  let found: AttrDef | undefined;
  for (const part of path.split(".")) {
    found = list?.find((a) => a.name === part);
    if (!found) return undefined;
    list = found.children;
  }
  return found;
}

export function searchCatalog(query: string, provider?: ProviderId): CatalogEntry[] {
  const q = query.trim().toLowerCase();
  const list = catalogEntries(provider);
  if (!q) return list;
  const words = q.split(/\s+/).filter(Boolean);
  const score = (r: CatalogEntry) => {
    const name = r.displayName.toLowerCase();
    const spaced = r.type.replace(/_/g, " ");
    // Hand-written entries rank a little higher than generated ones with the same match.
    const bonus = r.generated ? 0 : 5;
    if (r.type === q) return 100;
    if (name === q) return 90 + bonus;
    if (r.aliases?.some((a) => a === q)) return 80 + bonus;
    if (r.type.includes(q) || spaced.includes(q)) return 60 + bonus - Math.min(10, r.type.length / 10);
    if (name.includes(q)) return 50 + bonus;
    if (r.aliases?.some((a) => a.includes(q))) return 40 + bonus;
    const hay = `${spaced} ${name} ${r.service} ${r.category} ${(r.aliases ?? []).join(" ")}`.toLowerCase();
    if (words.length > 1 && words.every((w) => hay.includes(w))) return 30 + bonus;
    if (`${r.service} ${r.category}`.toLowerCase().includes(q)) return 20 + bonus;
    return 0;
  };
  return list
    .map((r) => [r, score(r)] as const)
    .filter(([, s]) => s > 0)
    .sort((a, b) => b[1] - a[1] || a[0].type.length - b[0].type.length)
    .map(([r]) => r);
}
